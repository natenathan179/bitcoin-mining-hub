/**
 * Splits the 159 KB location database (src/lib/marketplace-locations.json) into
 * small shards under src/lib/marketplace-shards/, each carrying its locations
 * plus the pre-computed "nearby" links those pages render.
 *
 * Why: rendering one city page used to parse the whole database and scan all
 * 1,075 locations for neighbours. On a cold Cloudflare isolate under crawler
 * concurrency that exceeded the worker CPU limit and returned 5xx.
 *
 * Re-run after any change to the location JSON:
 *   bun scripts/build-marketplace-shards.ts
 */
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";

import { MARKET_LOCATIONS, relatedLocations } from "../src/lib/marketplace";

const OUT = "src/lib/marketplace-shards";
const SHARDS = 24;

function shardOf(slug: string): number {
  let h = 0;
  for (let i = 0; i < slug.length; i += 1) h = (h * 31 + slug.charCodeAt(i)) >>> 0;
  return h % SHARDS;
}

mkdirSync(OUT, { recursive: true });
for (const f of readdirSync(OUT)) rmSync(`${OUT}/${f}`);

type Entry = {
  loc: (typeof MARKET_LOCATIONS)[number];
  related: { slug: string; keyword: string }[];
};

const buckets: Entry[][] = Array.from({ length: SHARDS }, () => []);
for (const loc of MARKET_LOCATIONS) {
  buckets[shardOf(loc.slug)]!.push({
    loc,
    related: relatedLocations(loc, 12).map((r) => ({ slug: r.slug, keyword: r.keyword })),
  });
}

buckets.forEach((entries, i) => {
  writeFileSync(
    `${OUT}/shard-${i}.ts`,
    `// AUTO-GENERATED by scripts/build-marketplace-shards.ts — do not edit.\n` +
      `import type { LocationEntry } from "./types";\n\n` +
      `export const ENTRIES: LocationEntry[] = ${JSON.stringify(entries, null, 2)};\n`,
  );
});

writeFileSync(
  `${OUT}/types.ts`,
  `import type { MarketplaceLocation } from "../marketplace-page";

export interface LocationEntry {
  loc: MarketplaceLocation;
  related: { slug: string; keyword: string }[];
}
`,
);

const loaders = buckets.map((_, i) => `  () => import("./shard-${i}"),`).join("\n");

writeFileSync(
  `${OUT}/index.ts`,
  `// AUTO-GENERATED by scripts/build-marketplace-shards.ts — do not edit.
import type { LocationEntry } from "./types";

const SHARDS = ${SHARDS};

const loaders: Array<() => Promise<{ ENTRIES: LocationEntry[] }>> = [
${loaders}
];

function shardOf(slug: string): number {
  let h = 0;
  for (let i = 0; i < slug.length; i += 1) h = (h * 31 + slug.charCodeAt(i)) >>> 0;
  return h % SHARDS;
}

const cache = new Map<number, Map<string, LocationEntry>>();

/** Loads only the shard that can contain \\\`slug\\\`. */
export async function getLocationEntryAsync(slug: string): Promise<LocationEntry | null> {
  const i = shardOf(slug);
  let index = cache.get(i);
  if (!index) {
    const { ENTRIES } = await loaders[i]!();
    index = new Map(ENTRIES.map((e) => [e.loc.slug, e]));
    cache.set(i, index);
  }
  return index.get(slug) ?? null;
}
`,
);

console.log(
  `wrote ${SHARDS} shards for ${MARKET_LOCATIONS.length} locations; largest ${Math.max(
    ...buckets.map((b) => JSON.stringify(b).length),
  )} bytes`,
);
