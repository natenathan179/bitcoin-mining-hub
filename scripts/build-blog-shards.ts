/**
 * Splits the 2 MB article library (src/lib/blog.ts) into small shards under
 * src/lib/blog-shards/.
 *
 * Why: rendering one guide used to load the whole 2 MB module into the worker,
 * and compiling that on a cold isolate burns enough CPU that Cloudflare kills
 * concurrent requests with "worker exceeded resource limits" (HTTP 5xx during
 * an SEO crawl). A guide now loads only its own ~100 KB shard.
 *
 * blog.ts stays the editable source of truth. Re-run this script after any
 * change to it:  bun scripts/build-blog-shards.ts
 */
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";

import { BLOG_POSTS } from "../src/lib/blog";

const OUT = "src/lib/blog-shards";
const SHARDS = 24;

function shardOf(slug: string): number {
  let h = 0;
  for (let i = 0; i < slug.length; i += 1) h = (h * 31 + slug.charCodeAt(i)) >>> 0;
  return h % SHARDS;
}

mkdirSync(OUT, { recursive: true });
for (const f of readdirSync(OUT)) rmSync(`${OUT}/${f}`);

const buckets: (typeof BLOG_POSTS)[] = Array.from({ length: SHARDS }, () => []);
for (const post of BLOG_POSTS) buckets[shardOf(post.slug)]!.push(post);

buckets.forEach((posts, i) => {
  writeFileSync(
    `${OUT}/shard-${i}.ts`,
    `// AUTO-GENERATED by scripts/build-blog-shards.ts — do not edit.\n` +
      `import type { BlogPost } from "../blog-types";\n\n` +
      `export const POSTS: BlogPost[] = ${JSON.stringify(posts, null, 2)};\n`,
  );
});

const loaders = buckets
  .map((_, i) => `  () => import("./shard-${i}"),`)
  .join("\n");

writeFileSync(
  `${OUT}/index.ts`,
  `// AUTO-GENERATED by scripts/build-blog-shards.ts — do not edit.
import type { BlogPost } from "../blog-types";

const SHARDS = ${SHARDS};

const loaders: Array<() => Promise<{ POSTS: BlogPost[] }>> = [
${loaders}
];

function shardOf(slug: string): number {
  let h = 0;
  for (let i = 0; i < slug.length; i += 1) h = (h * 31 + slug.charCodeAt(i)) >>> 0;
  return h % SHARDS;
}

const cache = new Map<number, BlogPost[]>();

/** Loads only the shard that can contain \`slug\`. */
export async function getPostAsync(slug: string): Promise<BlogPost | null> {
  const i = shardOf(slug);
  let posts = cache.get(i);
  if (!posts) {
    posts = (await loaders[i]!()).POSTS;
    cache.set(i, posts);
  }
  return posts.find((p) => p.slug === slug) ?? null;
}
`,
);

console.log(
  `wrote ${SHARDS} shards for ${BLOG_POSTS.length} posts; largest ${Math.max(...buckets.map((b) => JSON.stringify(b).length))} bytes`,
);
